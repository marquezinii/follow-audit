const languageMenu = document.querySelector('#language-menu');
const activeLanguageLabel = document.querySelector('[data-active-language]');
const languageButtons = [...document.querySelectorAll('[data-language]')];
const themeToggle = document.querySelector('#theme-toggle');
const copyButtons = [...document.querySelectorAll('.copy-script')];
const feedbackElements = [...document.querySelectorAll('.copy-feedback')];
const description = document.querySelector('meta[name="description"]');
const storage = {
  get(key) {
    try { return localStorage.getItem(key); } catch { return null; }
  },
  set(key, value) {
    try { localStorage.setItem(key, value); } catch {}
  },
};

let activeLanguage = getInitialLanguage();

function getInitialLanguage() {
  const saved = storage.get('follow-audit:site-language');
  if (saved && translations[saved]) return saved;
  const browserLanguage = navigator.language.toLowerCase();
  if (browserLanguage.startsWith('pt')) return 'pt-BR';
  return Object.keys(translations).find((language) => browserLanguage.startsWith(language)) || 'en';
}

function applyLanguage(language) {
  activeLanguage = translations[language] ? language : 'en';
  const copy = translations[activeLanguage];
  document.documentElement.lang = activeLanguage;
  document.title = copy._page_title;
  description.content = copy._meta;
  activeLanguageLabel.textContent = activeLanguage === 'pt-BR' ? 'PT' : activeLanguage.toUpperCase();
  languageButtons.forEach((button) => {
    const isActive = button.dataset.language === activeLanguage;
    button.classList.toggle('is-active', isActive);
    button.setAttribute('aria-pressed', String(isActive));
  });
  document.querySelectorAll('[data-i18n]').forEach((element) => {
    const value = copy[element.dataset.i18n];
    if (value) element.textContent = value;
  });
  document.querySelectorAll('[data-i18n-aria-label]').forEach((element) => {
    const value = copy[element.dataset.i18nAriaLabel];
    if (value) element.setAttribute('aria-label', value);
  });
  updateThemeControl();
}

function updateThemeControl() {
  const isDark = document.documentElement.dataset.theme === 'dark';
  const copy = translations[activeLanguage];
  themeToggle.setAttribute('aria-label', isDark ? copy.theme_light : copy.theme_dark);
  themeToggle.setAttribute('aria-pressed', String(isDark));
  document.querySelector('meta[name="theme-color"]').content = isDark ? '#061522' : '#f7fafc';
}

function applyTheme(theme) {
  document.documentElement.dataset.theme = theme;
  storage.set('follow-audit:site-theme', theme);
  updateThemeControl();
}

async function copyScript() {
  const copy = translations[activeLanguage];
  copyButtons.forEach((button) => {
    button.disabled = true;
    button.querySelector('[data-i18n]').textContent = copy.copying;
  });
  try {
    const response = await fetch('dist.js', { cache: 'no-store' });
    if (!response.ok) throw new Error(`HTTP ${response.status}`);
    const script = await response.text();
    if (script.length < 500) throw new Error('Incomplete bundle');
    await writeClipboard(script);
    feedbackElements.forEach((element) => { element.textContent = copy.copy_success; });
    copyButtons.forEach((button) => { button.querySelector('[data-i18n]').textContent = copy.copied; });
  } catch {
    feedbackElements.forEach((element) => { element.textContent = copy.copy_error; });
  } finally {
    copyButtons.forEach((button) => { button.disabled = false; });
    setTimeout(() => {
      const currentCopy = translations[activeLanguage];
      copyButtons.forEach((button) => { button.querySelector('[data-i18n]').textContent = currentCopy.copy_script; });
    }, 1600);
  }
}

async function writeClipboard(text) {
  if (navigator.clipboard?.writeText) {
    try {
      await navigator.clipboard.writeText(text);
      return;
    } catch {}
  }
  const fallback = document.createElement('textarea');
  fallback.value = text;
  fallback.setAttribute('readonly', '');
  fallback.style.position = 'fixed';
  fallback.style.opacity = '0';
  document.body.append(fallback);
  fallback.select();
  const copied = document.execCommand('copy');
  fallback.remove();
  if (!copied) throw new Error('Clipboard unavailable');
}

languageButtons.forEach((button) => button.addEventListener('click', () => {
  applyLanguage(button.dataset.language);
  storage.set('follow-audit:site-language', activeLanguage);
  languageMenu.open = false;
  feedbackElements.forEach((element) => { element.textContent = ''; });
}));

document.addEventListener('click', (event) => {
  if (!languageMenu.contains(event.target)) languageMenu.open = false;
});

document.addEventListener('keydown', (event) => {
  if (event.key === 'Escape' && languageMenu.open) {
    languageMenu.open = false;
    languageMenu.querySelector('summary').focus();
  }
});

themeToggle.addEventListener('click', () => {
  applyTheme(document.documentElement.dataset.theme === 'dark' ? 'light' : 'dark');
});

copyButtons.forEach((button) => button.addEventListener('click', copyScript));

const reveals = document.querySelectorAll('.reveal');
requestAnimationFrame(() => reveals.forEach((element) => element.classList.add('is-visible')));

