export function resolveLocale(saved: string | null, browserLanguage: string): Locale {
  if (locales.includes(saved as Locale)) return saved as Locale;
  const normalized = browserLanguage.toLowerCase();
  if (normalized.startsWith('pt')) return 'pt-BR';
  return locales.find(locale => normalized.startsWith(locale.toLowerCase())) ?? 'en';
}

export function format(copy: Copy, key: CopyKey, values: Record<string, string | number> = {}): string {
  return copy[key].replace(/\{(\w+)\}/g, (match, name: string) => String(values[name] ?? match));
}
